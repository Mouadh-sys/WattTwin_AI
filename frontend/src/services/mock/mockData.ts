/**
 * Generates synthetic telemetry timeline for analytics and charts
 */
export function generateSyntheticTimeline(samples = 24): TelemetrySample[] {
  const result: TelemetrySample[] = [];
  const baseTotal = 24.5;

  for (let i = 0; i < samples; i++) {
    const timeSec = i * 150;
    const hour = Math.floor(timeSec / 3600);
    const minute = Math.floor((timeSec % 3600) / 60);
    const timeLabel = `${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}`;

    // Periodic cycling of machining and packaging
    const millingCycle = Math.sin((i / samples) * Math.PI * 4);
    const packagingCycle = Math.cos((i / samples) * Math.PI * 3);

    const conveyor = 2.8 + Math.sin(i * 0.5) * 0.15;
    const processing = 11.0 + millingCycle * 3.5;
    const sorting = 3.8 + Math.cos(i * 0.7) * 0.4;
    const packaging = 1.8 + (packagingCycle > 0 ? 3.8 : 0);

    const totalPower = Number((conveyor + processing + sorting + packaging).toFixed(2));
    const baselinePower = Number((totalPower + 4.2 + (packagingCycle <= 0 ? 2.5 : 0)).toFixed(2));

    const cumulativeEnergy = Number((i * 4.1 + totalPower * 0.15).toFixed(2));
    const baselineEnergy = Number((cumulativeEnergy * 1.22).toFixed(2));
    const units = Math.floor(i * 10.5);

    result.push({
      timestamp: timeLabel,
      timeSeconds: timeSec,
      totalPowerKw: totalPower,
      baselinePowerKw: baselinePower,
      conveyorPowerKw: Number(conveyor.toFixed(2)),
      processingPowerKw: Number(processing.toFixed(2)),
      sortingPowerKw: Number(sorting.toFixed(2)),
      packagingPowerKw: Number(packaging.toFixed(2)),
      cumulativeEnergyKwh: cumulativeEnergy,
      baselineEnergyKwh: baselineEnergy,
      unitsProduced: units,
      conformingUnits: Math.floor(units * 0.97),
      defectiveUnits: Math.ceil(units * 0.03),
      instantThroughputUph: Number((58 + Math.sin(i * 0.4) * 4).toFixed(1)),
      activeResidualKw: Number((Math.random() * 0.15 + 0.02).toFixed(3)),
    });
  }

  return result;
}
